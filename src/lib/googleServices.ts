/**
 * 3. GOOGLE DOCS / DRIVE: Create a formatted document or download package
 */
export function exportToGoogleDocs(noteTitle: string, noteContent: string): {
  copySuccess: boolean;
  googleDocsCreateUrl: string;
} {
  const createUrl = 'https://docs.google.com/document/create';
  
  // Copy formatted content to system clipboard so user can instantly paste into new Google Doc
  let copySuccess = false;
  if (typeof navigator !== 'undefined' && navigator.clipboard) {
    const formattedDoc = `# ${noteTitle}
${new Date().toLocaleDateString('en-US', { dateStyle: 'full' })}
Study Top 2.0 Academic Notes

${noteContent}

—
Created in Study Top 2.0 (https://tinyurl.com/studytop2026)`;
    
    try {
      navigator.clipboard.writeText(formattedDoc);
      copySuccess = true;
    } catch (_) {}
  }
  
  return {
    copySuccess,
    googleDocsCreateUrl: createUrl
  };
}

/**
 * 4. GOOGLE SEARCH GROUNDING: Query live academic data grounded with real Google Search
 */
export async function queryGoogleSearchGrounding(
  query: string,
  subject?: string,
  topic?: string
): Promise<GoogleSearchGroundingResult> {
  const res = await fetch('/api/google/search-grounding', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ query, subject, topic })
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err.error || `Google Search Grounding failed (${res.status})`);
  }

  const data = await res.json();
  return {
    answer: data.answer,
    sources: data.sources || [],
    searchQueries: data.searchQueries || [],
    renderedContent: data.renderedContent
  };
}

/**
 * 5. GOOGLE DRIVE: Check if OAuth access token is active
 */
export async function getGoogleWorkspaceAuthStatus(): Promise<{
  isAuthenticated: boolean;
  token: string | null;
}> {
  try {
    const token = await getAccessToken();
    return {
      isAuthenticated: Boolean(token),
      token
    };
  } catch (_) {
    return {
      isAuthenticated: false,
      token: null
    };
  }
}
