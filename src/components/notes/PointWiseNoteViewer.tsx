import React, { useState, useMemo, useRef } from 'react';
import { 
  ArrowLeft, 
  Download, 
  Copy, 
  Check, 
  Share2, 
  Trash2, 
  Search, 
  Sparkles, 
  BookOpen, 
  ChevronDown, 
  ChevronUp, 
  Layers, 
  FileText, 
  Calculator, 
  Award, 
  HelpCircle, 
  Clock, 
  CheckCircle2, 
  Printer,
  Calendar,
  Zap,
  Tag,
  ZoomIn,
  ZoomOut,
  Image as ImageIcon,
  CheckCircle,
  Bookmark,
  ChevronRight,
  SlidersHorizontal as Sliders
} from 'lucide-react';
import ReactMarkdown from 'react-markdown';
import remarkMath from 'remark-math';
import rehypeKatex from 'rehype-katex';
import 'katex/dist/katex.min.css';
import { jsPDF } from 'jspdf';
import html2canvas from 'html2canvas';
import { Note } from '../../types';
import { MermaidViewer } from '../MermaidViewer';
import { StudyTopLogo } from '../StudyTopLogo';

interface PointWiseNoteViewerProps {
  note: Note;
  onBack: () => void;
  onDeleteNote?: (id: string) => void;
  onSaveToFavorites?: (id: string) => void;
  language?: string;
}

export const PointWiseNoteViewer: React.FC<PointWiseNoteViewerProps> = ({
  note,
  onBack,
  onDeleteNote,
  onSaveToFavorites,
  language = 'English'
}) => {
  const [searchQuery, setSearchQuery] = useState('');
  const [copied, setCopied] = useState(false);
  const [shared, setShared] = useState(false);
  const [isDownloadingPdf, setIsDownloadingPdf] = useState(false);
  const [isDownloadingImage, setIsDownloadingImage] = useState(false);
  const [collapsedSections, setCollapsedSections] = useState<Record<string, boolean>>({});
  const [activeSectionTab, setActiveSectionTab] = useState<string>('all');
  const [isDeleteModalOpen, setIsDeleteModalOpen] = useState(false);
  const [revealedMcqAnswers, setRevealedMcqAnswers] = useState<Record<number, boolean>>({});
  const [fontSizeLevel, setFontSizeLevel] = useState<'normal' | 'large' | 'xl'>('normal');

  const noteContentRef = useRef<HTMLDivElement>(null);

  // Toggle individual section collapse
  const toggleSection = (sectionKey: string) => {
    setCollapsedSections(prev => ({
      ...prev,
      [sectionKey]: !prev[sectionKey]
    }));
  };

  // Structured note data if provided, or parse/extract from content
  const structured = useMemo(() => {
    if (note.structuredData && typeof note.structuredData === 'object') {
      return note.structuredData;
    }
    try {
      const match = note.content?.match(/<!--MIND_STRUCTURED:([\s\S]*?)-->/);
      if (match && match[1]) {
        return JSON.parse(match[1]);
      }
    } catch (e) {}
    return null;
  }, [note]);

  // Copy full note markdown
  const handleCopy = () => {
    navigator.clipboard.writeText(note.content || '');
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  // Share note
  const handleShare = () => {
    if (navigator.share) {
      navigator.share({
        title: note.title,
        text: `Study Top Notes: ${note.title}\n\n${(note.content || '').substring(0, 300)}...`
      }).catch(() => {});
    } else {
      handleCopy();
      setShared(true);
      setTimeout(() => setShared(false), 2000);
    }
  };

  // Download high-resolution PDF
  const handleDownloadPdf = async () => {
    setIsDownloadingPdf(true);
    try {
      const doc = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4'
      });

      const title = note.title || 'Study Top Notes';
      
      // Page 1 Header
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(20);
      doc.setTextColor(15, 23, 42); // slate-900
      doc.text(title, 15, 20);

      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(71, 85, 105); // slate-600
      doc.text(`Study Top • Generated by MIND 1.0 • ${new Date(note.updatedAt || Date.now()).toLocaleDateString()}`, 15, 27);

      doc.setDrawColor(203, 213, 225);
      doc.line(15, 31, 195, 31);

      const splitText = doc.splitTextToSize(
        (note.content || '')
          .replace(/[#*`_]/g, '')
          .replace(/<!--[\s\S]*?-->/g, '')
          .trim(),
        180
      );

      let y = 40;
      let pageNum = 1;

      for (const line of splitText) {
        if (y > 275) {
          // Footer
          doc.setFontSize(8);
          doc.setTextColor(148, 163, 184);
          doc.text(`Study Top — Page ${pageNum}`, 105, 290, { align: 'center' });
          
          doc.addPage();
          pageNum++;
          y = 20;
        }
        doc.setFontSize(10);
        doc.setTextColor(30, 41, 59);
        doc.text(line, 15, y);
        y += 6;
      }

      // Final page footer
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(`Study Top — Page ${pageNum}`, 105, 290, { align: 'center' });

      doc.save(`${title.replace(/[^a-zA-Z0-9]/g, '_')}_StudyTop_Notes.pdf`);
    } catch (e) {
      console.error('PDF Download Error:', e);
    } finally {
      setIsDownloadingPdf(false);
    }
  };

  // Download Note as PNG Image
  const handleDownloadImage = async () => {
    if (!noteContentRef.current) return;
    setIsDownloadingImage(true);
    try {
      const canvas = await html2canvas(noteContentRef.current, {
        scale: 2,
        backgroundColor: '#f8fafc',
        useCORS: true
      });
      const dataUrl = canvas.toDataURL('image/png');
      const a = document.createElement('a');
      a.href = dataUrl;
      a.download = `${(note.title || 'study_notes').replace(/[^a-zA-Z0-9]/g, '_')}.png`;
      a.click();
    } catch (e) {
      console.error('Image Export Error:', e);
    } finally {
      setIsDownloadingImage(false);
    }
  };

  // Navigation sections list
  const navSections = [
    { id: 'all', label: 'All Notes' },
    { id: 'overview', label: 'Overview' },
    { id: 'definitions', label: 'Definitions' },
    { id: 'concepts', label: 'Main Concepts' },
    { id: 'explanations', label: 'Point-Wise Details' },
    { id: 'formulas', label: 'Formulas & Math' },
    { id: 'questions', label: 'Exam Q&A & MCQs' },
    { id: 'summary', label: 'Quick Revision' }
  ];

  return (
    <div className="min-h-screen w-full bg-slate-50 font-sans text-slate-900 pb-24 selection:bg-blue-100">
      
      {/* Top Reading Navigation Bar */}
      <header className="sticky top-0 z-30 bg-white/95 backdrop-blur-md border-b border-slate-200/90 shadow-2xs px-4 sm:px-8 py-3.5 flex items-center justify-between gap-4">
        
        {/* Back and Title */}
        <div className="flex items-center gap-3 min-w-0">
          <button
            onClick={onBack}
            className="p-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 transition cursor-pointer shrink-0"
            title="Back to Notes List"
          >
            <ArrowLeft className="w-4 h-4" />
          </button>
          
          <div className="flex items-center gap-2.5 min-w-0">
            <StudyTopLogo size="sm" variant="icon" />
            <div className="min-w-0">
              <div className="flex items-center gap-2">
                <span className="px-2 py-0.5 rounded-full bg-blue-100 text-blue-800 text-[10px] font-black uppercase tracking-wider">
                  MIND 1.0 Point-Wise Notes
                </span>
                <span className="text-xs text-slate-400 font-medium hidden sm:inline">
                  Read-Only Study Interface
                </span>
              </div>
              <h1 className="text-sm sm:text-base font-black text-slate-900 truncate">
                {note.title || 'Untitled Study Guide'}
              </h1>
            </div>
          </div>
        </div>

        {/* Action Controls: Zoom, Copy, Download PDF, Download Image, Share, Delete */}
        <div className="flex items-center gap-1.5 sm:gap-2 shrink-0">
          
          {/* Zoom / Font Size Selector */}
          <div className="hidden md:flex items-center bg-slate-100 p-0.5 rounded-xl border border-slate-200">
            <button
              onClick={() => setFontSizeLevel('normal')}
              className={`px-2 py-1 rounded-lg text-xs font-bold transition cursor-pointer ${fontSizeLevel === 'normal' ? 'bg-white text-blue-600 shadow-2xs' : 'text-slate-500'}`}
              title="Normal Text Size"
            >
              A
            </button>
            <button
              onClick={() => setFontSizeLevel('large')}
              className={`px-2 py-1 rounded-lg text-xs font-extrabold transition cursor-pointer ${fontSizeLevel === 'large' ? 'bg-white text-blue-600 shadow-2xs' : 'text-slate-500'}`}
              title="Large Text Size"
            >
              A+
            </button>
            <button
              onClick={() => setFontSizeLevel('xl')}
              className={`px-2 py-1 rounded-lg text-sm font-black transition cursor-pointer ${fontSizeLevel === 'xl' ? 'bg-white text-blue-600 shadow-2xs' : 'text-slate-500'}`}
              title="Extra Large Text Size"
            >
              A++
            </button>
          </div>

          <button
            onClick={handleCopy}
            className="px-3 py-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-bold transition flex items-center gap-1.5 cursor-pointer"
            title="Copy Note Markdown"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5 text-slate-500" />}
            <span className="hidden sm:inline">{copied ? 'Copied' : 'Copy'}</span>
          </button>

          <button
            onClick={handleDownloadPdf}
            disabled={isDownloadingPdf}
            className="px-3 py-2 rounded-xl bg-blue-50 hover:bg-blue-100 text-blue-700 text-xs font-bold transition flex items-center gap-1.5 cursor-pointer disabled:opacity-50"
            title="Download PDF"
          >
            <Download className="w-3.5 h-3.5" />
            <span className="hidden sm:inline">{isDownloadingPdf ? 'Exporting...' : 'PDF'}</span>
          </button>

          <button
            onClick={handleDownloadImage}
            disabled={isDownloadingImage}
            className="p-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 transition cursor-pointer"
            title="Download as PNG Image"
          >
            <ImageIcon className="w-4 h-4 text-slate-500" />
          </button>

          <button
            onClick={handleShare}
            className="p-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 transition cursor-pointer"
            title="Share Notes"
          >
            <Share2 className="w-4 h-4 text-slate-500" />
          </button>

          {onDeleteNote && (
            <button
              onClick={() => setIsDeleteModalOpen(true)}
              className="p-2 rounded-xl bg-rose-50 hover:bg-rose-100 text-rose-600 transition cursor-pointer"
              title="Delete Note"
            >
              <Trash2 className="w-4 h-4" />
            </button>
          )}
        </div>
      </header>

      {/* Main Container */}
      <div 
        ref={noteContentRef}
        className={`max-w-5xl mx-auto px-4 sm:px-6 pt-6 space-y-6 ${
          fontSizeLevel === 'large' ? 'text-sm' : (fontSizeLevel === 'xl' ? 'text-base' : 'text-xs')
        }`}
      >
        
        {/* =========================================================================
            PAGE 1 — CHAPTER OVERVIEW CARD
            ========================================================================= */}
        <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-8 shadow-xs space-y-4">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
            <div className="flex items-center gap-3">
              <StudyTopLogo size="sm" variant="icon" />
              <div className="flex flex-wrap items-center gap-2">
                <span className="px-3 py-1 rounded-full bg-blue-600 text-white text-xs font-black uppercase tracking-wider">
                  {structured?.subject || note.categoryId || 'Academic Studies'}
                </span>
                <span className="px-2.5 py-1 rounded-full bg-indigo-50 border border-indigo-200 text-indigo-700 text-xs font-bold uppercase tracking-wider flex items-center gap-1">
                  <Sparkles className="w-3.5 h-3.5 text-indigo-600" />
                  MIND 1.0 Note Engine
                </span>
              </div>
            </div>

            <div className="flex items-center gap-3 text-xs text-slate-400 font-medium">
              <span className="flex items-center gap-1">
                <Clock className="w-3.5 h-3.5 text-slate-400" />
                <span>{structured?.readingTimeMinutes || 7} mins read</span>
              </span>
              <span>•</span>
              <span>{new Date(note.updatedAt || Date.now()).toLocaleDateString()}</span>
            </div>
          </div>

          <div>
            <h2 className="text-2xl sm:text-3xl font-black text-slate-900 tracking-tight">
              {structured?.chapterTitle || note.title}
            </h2>
            {structured?.topicName && (
              <p className="text-xs sm:text-sm text-blue-600 font-bold mt-1">
                Focus Topic: {structured.topicName}
              </p>
            )}
          </div>

          {/* Learning Objectives */}
          {structured?.learningObjectives && structured.learningObjectives.length > 0 && (
            <div className="p-4 rounded-2xl bg-slate-50 border border-slate-200 space-y-2">
              <span className="text-xs font-black text-slate-700 uppercase tracking-wider flex items-center gap-1.5">
                <Award className="w-4 h-4 text-blue-600" />
                <span>Learning Objectives</span>
              </span>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
                {structured.learningObjectives.map((obj: string, i: number) => (
                  <div key={i} className="flex items-start gap-2 text-xs font-semibold text-slate-700">
                    <span className="text-blue-600 font-bold">✓</span>
                    <span>{obj}</span>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* In-Note Search Bar */}
          <div className="relative pt-2 border-t border-slate-100">
            <Search className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search concepts, formulas, questions in this note..."
              className="w-full bg-slate-50 border border-slate-200 rounded-xl pl-9 pr-3 py-2 text-xs font-semibold text-slate-900 outline-none focus:bg-white focus:border-blue-500"
            />
          </div>
        </div>

        {/* Section Navigation Tabs */}
        <div className="flex items-center gap-2 overflow-x-auto pb-1 scrollbar-none">
          {navSections.map(sec => (
            <button
              key={sec.id}
              onClick={() => setActiveSectionTab(sec.id)}
              className={`px-3.5 py-2 rounded-xl text-xs font-bold shrink-0 transition cursor-pointer flex items-center gap-1.5 ${
                activeSectionTab === sec.id
                  ? 'bg-blue-600 text-white shadow-xs'
                  : 'bg-white border border-slate-200 text-slate-600 hover:bg-slate-100'
              }`}
            >
              <span>{sec.label}</span>
            </button>
          ))}
        </div>

        {/* =========================================================================
            PAGE 2 ONWARDS — DETAILED POINT-WISE SECTIONS
            ========================================================================= */}
        {structured ? (
          <div className="space-y-6">
            
            {/* SECTION 1: INTRODUCTION & OVERVIEW */}
            {(activeSectionTab === 'all' || activeSectionTab === 'overview') && structured.introduction && (
              <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-7 shadow-xs space-y-3">
                <div 
                  onClick={() => toggleSection('intro')}
                  className="flex items-center justify-between cursor-pointer select-none"
                >
                  <h3 className="text-base font-black text-slate-900 flex items-center gap-2">
                    <BookOpen className="w-5 h-5 text-blue-600" />
                    <span>Section 1: Introduction &amp; Core Overview</span>
                  </h3>
                  {collapsedSections['intro'] ? <ChevronDown className="w-4 h-4 text-slate-400" /> : <ChevronUp className="w-4 h-4 text-slate-400" />}
                </div>

                {!collapsedSections['intro'] && (
                  <div className="pt-2 border-t border-slate-100 text-slate-700 leading-relaxed font-medium">
                    {structured.introduction}
                  </div>
                )}
              </div>
            )}

            {/* SECTIONS: CHAPTER SUB-SECTIONS WITH NUMBERED POINT-WISE LISTS */}
            {(activeSectionTab === 'all' || activeSectionTab === 'concepts' || activeSectionTab === 'explanations') && structured.sections?.length > 0 && (
              <div className="space-y-4">
                {structured.sections.map((sec: any, idx: number) => (
                  <div key={idx} className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-7 shadow-xs space-y-3">
                    <h3 className="text-base font-black text-slate-900 flex items-center gap-2">
                      <Layers className="w-5 h-5 text-indigo-600" />
                      <span>Section {sec.sectionNumber || idx + 2}: {sec.title}</span>
                    </h3>

                    {sec.overview && (
                      <p className="text-slate-600 font-medium leading-relaxed">{sec.overview}</p>
                    )}

                    {sec.points && sec.points.length > 0 && (
                      <div className="p-4 rounded-2xl bg-slate-50 border border-slate-200/80 space-y-2">
                        <span className="text-xs font-black text-indigo-900 uppercase tracking-wider block">
                          Important Points:
                        </span>
                        <ul className="space-y-2">
                          {sec.points.map((pt: string, pIdx: number) => (
                            <li key={pIdx} className="text-slate-700 font-medium flex items-start gap-2.5">
                              <span className="w-5 h-5 rounded-full bg-indigo-100 text-indigo-700 font-bold text-xs flex items-center justify-center shrink-0 mt-0.5">
                                {pIdx + 1}
                              </span>
                              <span className="leading-relaxed">{pt}</span>
                            </li>
                          ))}
                        </ul>
                      </div>
                    )}
                  </div>
                ))}
              </div>
            )}

            {/* SECTION 2: IMPORTANT DEFINITIONS */}
            {(activeSectionTab === 'all' || activeSectionTab === 'definitions') && structured.definitions?.length > 0 && (
              <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-7 shadow-xs space-y-4">
                <div 
                  onClick={() => toggleSection('definitions')}
                  className="flex items-center justify-between cursor-pointer select-none"
                >
                  <h3 className="text-base font-black text-slate-900 flex items-center gap-2">
                    <Tag className="w-5 h-5 text-emerald-600" />
                    <span>Key Definitions &amp; Academic Terms ({structured.definitions.length})</span>
                  </h3>
                  {collapsedSections['definitions'] ? <ChevronDown className="w-4 h-4 text-slate-400" /> : <ChevronUp className="w-4 h-4 text-slate-400" />}
                </div>

                {!collapsedSections['definitions'] && (
                  <div className="grid grid-cols-1 md:grid-cols-2 gap-3.5 pt-2 border-t border-slate-100">
                    {structured.definitions.map((def: any, idx: number) => (
                      <div key={idx} className="p-4 rounded-2xl bg-emerald-50/40 border border-emerald-200/80 space-y-1.5 shadow-2xs">
                        <span className="px-2.5 py-0.5 rounded-full bg-emerald-200/80 text-emerald-900 text-xs font-black uppercase tracking-wider inline-block">
                          {def.term}
                        </span>
                        <p className="text-slate-700 font-medium leading-relaxed">
                          {def.definition}
                        </p>
                      </div>
                    ))}
                  </div>
                )}
              </div>
            )}

            {/* SECTION 3: FORMULA CARDS */}
            {(activeSectionTab === 'all' || activeSectionTab === 'formulas') && structured.formulas?.length > 0 && (
              <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-7 shadow-xs space-y-4">
                <div 
                  onClick={() => toggleSection('formulas')}
                  className="flex items-center justify-between cursor-pointer select-none"
                >
                  <h3 className="text-base font-black text-slate-900 flex items-center gap-2">
                    <Calculator className="w-5 h-5 text-amber-600" />
                    <span>Important Formulas &amp; Equations ({structured.formulas.length})</span>
                  </h3>
                  {collapsedSections['formulas'] ? <ChevronDown className="w-4 h-4 text-slate-400" /> : <ChevronUp className="w-4 h-4 text-slate-400" />}
                </div>

                {!collapsedSections['formulas'] && (
                  <div className="grid grid-cols-1 md:grid-cols-2 gap-4 pt-2 border-t border-slate-100">
                    {structured.formulas.map((f: any, idx: number) => (
                      <div key={idx} className="p-4 rounded-2xl bg-amber-50/40 border border-amber-200/80 space-y-2 shadow-2xs">
                        <span className="text-xs font-black text-amber-900 block">{f.name}</span>
                        <div className="p-3 bg-white rounded-xl border border-amber-200 font-mono text-center text-sm font-bold text-slate-900 overflow-x-auto">
                          $${f.formula}$$
                        </div>
                        {f.symbolExplanation && (
                          <p className="text-xs text-slate-600 font-medium">
                            <strong>Symbols:</strong> {f.symbolExplanation}
                          </p>
                        )}
                        {f.units && (
                          <p className="text-xs text-amber-800 font-bold">
                            <strong>Units:</strong> {f.units}
                          </p>
                        )}
                        <p className="text-xs text-slate-500 italic">{f.explanation}</p>
                      </div>
                    ))}
                  </div>
                )}
              </div>
            )}

            {/* SECTION 4: EXAMPLES & SCENARIOS */}
            {(activeSectionTab === 'all' || activeSectionTab === 'concepts') && structured.examples?.length > 0 && (
              <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-7 shadow-xs space-y-4">
                <h3 className="text-base font-black text-slate-900 flex items-center gap-2">
                  <CheckCircle2 className="w-5 h-5 text-blue-600" />
                  <span>Examples &amp; Real-World Scenarios</span>
                </h3>

                <div className="space-y-3">
                  {structured.examples.map((ex: any, idx: number) => (
                    <div key={idx} className="p-4 rounded-2xl bg-slate-50 border border-slate-200 space-y-2">
                      <span className="text-xs font-black text-blue-900 uppercase tracking-wider block">
                        Example {idx + 1}: {ex.title}
                      </span>
                      <p className="text-slate-700 font-medium"><strong>Scenario:</strong> {ex.scenario}</p>
                      <div className="p-3 rounded-xl bg-blue-50/50 border border-blue-200/70 text-slate-800 font-medium">
                        <strong>Solution:</strong> {ex.solution}
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* SECTION 5: COMPARISON TABLES */}
            {(activeSectionTab === 'all' || activeSectionTab === 'concepts') && structured.comparisons?.length > 0 && (
              <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-7 shadow-xs space-y-4">
                <h3 className="text-base font-black text-slate-900 flex items-center gap-2">
                  <Sliders className="w-5 h-5 text-indigo-600" />
                  <span>Important Differences &amp; Comparisons</span>
                </h3>

                <div className="overflow-x-auto">
                  <table className="w-full text-left border-collapse text-xs sm:text-sm">
                    <thead>
                      <tr className="bg-slate-100 text-slate-700 border-b border-slate-200">
                        <th className="p-3 font-black">Criteria / Feature</th>
                        <th className="p-3 font-black">Item A</th>
                        <th className="p-3 font-black">Item B</th>
                      </tr>
                    </thead>
                    <tbody>
                      {structured.comparisons.map((c: any, idx: number) => (
                        <tr key={idx} className="border-b border-slate-100 hover:bg-slate-50/50">
                          <td className="p-3 font-bold text-slate-900">{c.feature}</td>
                          <td className="p-3 text-slate-700 font-medium">{c.itemA}</td>
                          <td className="p-3 text-slate-700 font-medium">{c.itemB}</td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              </div>
            )}

            {/* SECTION 6: DIAGRAMS & FLOWCHARTS */}
            {structured.diagramCode && (
              <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-7 shadow-xs space-y-4">
                <h3 className="text-base font-black text-slate-900 flex items-center gap-2">
                  <Sparkles className="w-5 h-5 text-purple-600" />
                  <span>Concept Diagram &amp; Flowchart</span>
                </h3>
                <div className="p-5 bg-slate-50 rounded-2xl border border-slate-200 overflow-x-auto flex justify-center">
                  <MermaidViewer chart={structured.diagramCode} />
                </div>
                {structured.diagramDescription && (
                  <p className="text-xs text-slate-500 font-medium text-center italic">
                    {structured.diagramDescription}
                  </p>
                )}
              </div>
            )}

            {/* SECTION 7: EXAM-IMPORTANT QUESTIONS & MCQS */}
            {(activeSectionTab === 'all' || activeSectionTab === 'questions') && (
              <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-7 shadow-xs space-y-6">
                <h3 className="text-base font-black text-slate-900 flex items-center gap-2">
                  <Award className="w-5 h-5 text-rose-600" />
                  <span>Exam-Important Questions &amp; Practice</span>
                </h3>

                {/* Very Short Questions */}
                {structured.veryShortQuestions?.length > 0 && (
                  <div className="space-y-2.5">
                    <span className="text-xs font-black text-slate-700 uppercase tracking-wider block">
                      Very Short Answer Questions (1 Mark)
                    </span>
                    {structured.veryShortQuestions.map((vsq: any, i: number) => (
                      <div key={i} className="p-3.5 rounded-xl bg-slate-50 border border-slate-200">
                        <p className="text-xs font-bold text-slate-900">Q{i + 1}: {vsq.question}</p>
                        <p className="text-xs text-slate-600 font-medium mt-1">Ans: {vsq.answer}</p>
                      </div>
                    ))}
                  </div>
                )}

                {/* Short Questions */}
                {structured.shortQuestions?.length > 0 && (
                  <div className="space-y-2.5">
                    <span className="text-xs font-black text-slate-700 uppercase tracking-wider block">
                      Short Answer Questions (2–3 Marks)
                    </span>
                    {structured.shortQuestions.map((sq: any, i: number) => (
                      <div key={i} className="p-4 rounded-2xl bg-rose-50/40 border border-rose-100 space-y-1">
                        <p className="text-xs font-black text-rose-900">Q{i + 1}: {sq.question}</p>
                        <p className="text-xs text-slate-700 font-medium pl-3 border-l-2 border-rose-400 mt-1">{sq.answer}</p>
                      </div>
                    ))}
                  </div>
                )}

                {/* Long Answer Questions */}
                {structured.longQuestions?.length > 0 && (
                  <div className="space-y-3">
                    <span className="text-xs font-black text-slate-700 uppercase tracking-wider block">
                      Long Answer Comprehensive Questions (5 Marks)
                    </span>
                    {structured.longQuestions.map((lq: any, i: number) => (
                      <div key={i} className="p-4 rounded-2xl bg-slate-50 border border-slate-200 space-y-2">
                        <p className="text-xs font-black text-slate-900">Q{i + 1}: {lq.question}</p>
                        <div className="text-xs text-slate-700 font-medium pl-3 border-l-2 border-blue-500 leading-relaxed">
                          {lq.answer}
                        </div>
                      </div>
                    ))}
                  </div>
                )}

                {/* MCQs with Interactive Answer Reveal */}
                {structured.mcqs?.length > 0 && (
                  <div className="space-y-3 pt-2 border-t border-slate-100">
                    <span className="text-xs font-black text-slate-700 uppercase tracking-wider block">
                      Multiple Choice Practice Questions (MCQs)
                    </span>
                    {structured.mcqs.map((mcq: any, i: number) => (
                      <div key={i} className="p-4 rounded-2xl bg-slate-50 border border-slate-200 space-y-2">
                        <p className="text-xs font-black text-slate-900">Q{i + 1}: {mcq.question}</p>
                        <div className="grid grid-cols-1 sm:grid-cols-2 gap-1.5 pt-1">
                          {mcq.options?.map((opt: string, optIdx: number) => (
                            <div key={optIdx} className="p-2 rounded-xl bg-white border border-slate-200 text-xs font-semibold text-slate-700">
                              {opt}
                            </div>
                          ))}
                        </div>

                        <div className="pt-2">
                          {revealedMcqAnswers[i] ? (
                            <div className="p-2.5 rounded-xl bg-emerald-50 border border-emerald-200 text-xs font-bold text-emerald-800">
                              ✓ Correct Answer: {mcq.answer}
                              {mcq.explanation && <p className="font-normal text-slate-600 mt-0.5">{mcq.explanation}</p>}
                            </div>
                          ) : (
                            <button
                              type="button"
                              onClick={() => setRevealedMcqAnswers(prev => ({ ...prev, [i]: true }))}
                              className="text-xs font-bold text-blue-600 hover:underline cursor-pointer"
                            >
                              Show Correct Answer →
                            </button>
                          )}
                        </div>
                      </div>
                    ))}
                  </div>
                )}
              </div>
            )}

            {/* SECTION 8: QUICK REVISION POINTS */}
            {(activeSectionTab === 'all' || activeSectionTab === 'summary') && structured.quickRevision?.length > 0 && (
              <div className="bg-gradient-to-r from-blue-600 to-indigo-600 text-white rounded-3xl p-6 sm:p-8 shadow-md space-y-4">
                <div className="flex items-center gap-2">
                  <Zap className="w-5 h-5 text-amber-300" />
                  <h3 className="text-base font-black uppercase tracking-wider text-white">
                    Section 8: Quick Exam Revision Takeaways
                  </h3>
                </div>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                  {structured.quickRevision.map((qr: string, idx: number) => (
                    <div key={idx} className="p-3.5 rounded-xl bg-white/10 backdrop-blur-xs border border-white/15 flex items-start gap-2">
                      <span className="text-amber-300 font-bold shrink-0">⚡</span>
                      <span className="text-xs text-blue-50 font-semibold leading-relaxed">{qr}</span>
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* SECTION 9: CHAPTER SUMMARY */}
            {(activeSectionTab === 'all' || activeSectionTab === 'summary') && structured.chapterSummary && (
              <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-7 shadow-xs space-y-2">
                <h3 className="text-base font-black text-slate-900 flex items-center gap-2">
                  <Bookmark className="w-5 h-5 text-blue-600" />
                  <span>Section 9: Complete Chapter Summary</span>
                </h3>
                <p className="text-slate-700 leading-relaxed font-medium pt-2">
                  {structured.chapterSummary}
                </p>
              </div>
            )}

          </div>
        ) : (
          /* STANDARD MARKDOWN READING INTERFACE */
          <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-10 shadow-xs">
            <article className="prose prose-slate max-w-none text-xs sm:text-sm font-medium leading-relaxed prose-headings:font-black prose-headings:text-slate-900 prose-a:text-blue-600 prose-code:text-indigo-600 prose-pre:bg-slate-900 prose-pre:text-slate-100">
              <ReactMarkdown
                remarkPlugins={[remarkMath]}
                rehypePlugins={[rehypeKatex]}
              >
                {note.content || 'No content available for this study note.'}
              </ReactMarkdown>
            </article>
          </div>
        )}

      </div>

      {/* Delete Confirmation Modal */}
      {isDeleteModalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-xs">
          <div className="bg-white rounded-3xl border border-slate-200 p-6 max-w-sm w-full space-y-4 shadow-2xl">
            <div className="w-12 h-12 rounded-2xl bg-rose-50 text-rose-600 flex items-center justify-center mx-auto">
              <Trash2 className="w-6 h-6" />
            </div>
            <div className="text-center">
              <h4 className="text-base font-black text-slate-900">Delete this note?</h4>
              <p className="text-xs text-slate-500 mt-1">
                Are you sure you want to remove "{note.title}"? This cannot be undone.
              </p>
            </div>
            <div className="flex gap-2">
              <button
                onClick={() => setIsDeleteModalOpen(false)}
                className="flex-1 py-2.5 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 font-bold text-xs cursor-pointer"
              >
                Cancel
              </button>
              <button
                onClick={() => {
                  if (onDeleteNote) onDeleteNote(note.id);
                  setIsDeleteModalOpen(false);
                  onBack();
                }}
                className="flex-1 py-2.5 rounded-xl bg-rose-600 hover:bg-rose-700 text-white font-bold text-xs cursor-pointer shadow-xs"
              >
                Delete Note
              </button>
            </div>
          </div>
        </div>
      )}

    </div>
  );
};
