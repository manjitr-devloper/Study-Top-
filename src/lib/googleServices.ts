import { getAccessToken } from './firebase';

export interface GoogleCalendarEventInput {
  title: string;
  details: string;
  startDate?: Date;
  endDate?: Date;
  location?: string;
  tags?: string[];
}

export interface GoogleSearchGroundingSource {
  title: string;
  url: string;
}

export interface GoogleSearchGroundingResult {
  answer: string;
  sources: GoogleSearchGroundingSource[];
  searchQueries: string[];
  renderedContent?: string;
}

/**
 * 1. GOOGLE CALENDAR: Generate 1-Click Web Intent URL
 * Works seamlessly in all browsers without requiring intrusive calendar write permissions.
 */
export function buildGoogleCalendarEventUrl(input: GoogleCalendarEventInput): string {
  const base = 'https://calendar.google.com/calendar/render?action=TEMPLATE';
  const title = encodeURIComponent(`Study Top: ${input.title}`);
  
  const enrichedDetails = `${input.details}

—
Generated by Study Top 2.0 (AI Academic Workspace)
Link: https://tinyurl.com/studytop2026`;
  const details = encodeURIComponent(enrichedDetails);
  
  const start = input.startDate || new Date(Date.now() + 60 * 60 * 1000); // 1 hr from now
  const end = input.endDate || new Date(start.getTime() + 60 * 60 * 1000); // 1 hr session
  
  // Format as YYYYMMDDTHHmmssZ
  const formatIso = (d: Date) => d.toISOString().replace(/-|:|\.\d\d\d/g, '');
  const dates = `${formatIso(start)}/${formatIso(end)}`;
  
  let url = `${base}&text=${title}&details=${details}&dates=${dates}`;
  if (input.location) {
    url += `&location=${encodeURIComponent(input.location)}`;
  }
  return url;
}

